test('archivio corrotto conservato e scrittura fallita esplicita', async ({ page }) => {
  await start(page); await nav(page, 'Genitori e tutori');
  await page.getByRole('button', { name: 'Nuovo tutore' }).click();
  const modal = page.getByRole('dialog');
  await modal.getByLabel('Nome e cognome', { exact: true }).fill('Tutore non salvato');
  await modal.getByLabel('Relazione').fill('Genitore');
  await page.evaluate(() => { Storage.prototype.setItem = () => { throw new Error('Disco pieno simulato'); }; });
  await modal.getByRole('button', { name: 'Salva', exact: true }).click();
  await expect(modal.getByRole('alert')).toContainText('Disco pieno simulato');
  await page.reload(); await nav(page, 'Genitori e tutori');
  await expect(page.getByRole('heading', { name: 'Tutore non salvato' })).not.toBeVisible();
  await page.evaluate(() => localStorage.setItem('memoles-world:v1', '{corrotto'));
  await page.reload();
  await expect(page.getByRole('alert')).toContainText('Archivio locale corrotto');
  expect(await page.evaluate(() => localStorage.getItem('memoles-world:v1'))).toBe('{corrotto');
});
