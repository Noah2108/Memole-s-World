import { expect, test, type Page } from '@playwright/test';
import { screenshotPath } from './screenshots';

async function start(page: Page) {
  await page.clock.install({ time: new Date('2026-10-24T10:00:00Z') });
  await page.goto('/');
  await expect(page.getByRole('heading', { name: 'Bentornata Hoara' })).toBeVisible();
}
async function nav(page: Page, label: string) { await page.getByRole('navigation').getByRole('button', { name: label, exact: true }).click(); }

test('dashboard demo, mesi e layout MacBook senza errori o rete cloud', async ({ page }) => {
  const errors: string[] = [], external: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('request', r => { if (!r.url().startsWith('http://127.0.0.1:1431') && !r.url().startsWith('data:')) external.push(r.url()); });
  await start(page);
  await expect(page.getByTestId('expected')).toHaveText('770,00 €');
  await expect(page.getByTestId('received')).toHaveText('250,00 €');
  await expect(page.getByTestId('remaining')).toHaveText('520,00 €');
  await page.screenshot({ path: screenshotPath('panoramica-1440.png'), fullPage: true });
  await page.setViewportSize({ width: 1280, height: 800 });
  await page.screenshot({ path: screenshotPath('panoramica-1280.png'), fullPage: true });
  await page.screenshot({ path: screenshotPath('anteprima.png') });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole('button', { name: 'Mese successivo' }).click();
  await expect(page.getByTestId('expected')).toHaveText('0,00 €');
  await page.getByRole('button', { name: 'Prepara 6 scadenze' }).click();
  await page.getByRole('button', { name: 'Emetti scadenze', exact: true }).click();
  await expect(page.getByTestId('expected')).toHaveText('620,00 €');
  await page.reload();
  await page.getByRole('button', { name: 'Mese successivo' }).click();
  await expect(page.getByTestId('expected')).toHaveText('620,00 €');
  await page.getByRole('button', { name: 'Verifica rette del mese' }).click();
  await expect(page.getByRole('dialog')).toContainText('0 nuove scadenze');
  await page.keyboard.press('Escape');
  await page.getByLabel('Anno di riferimento').selectOption('2025');
  await page.getByLabel('Mese di riferimento', { exact: true }).selectOption('02');
  await expect(page.getByTestId('expected')).toHaveText('0,00 €');
  expect(errors).toEqual([]); expect(external).toEqual([]);
});

test('bambino e tutore, mensile, acconto, riapertura, storno e backup completo', async ({ page }) => {
  await start(page); await nav(page, 'Bambini');
  await page.getByRole('button', { name: 'Nuovo bambino', exact: true }).click();
  let modal = page.getByRole('dialog');
  await modal.getByLabel('Nome', { exact: true }).fill('Alice');
  await modal.getByLabel('Cognome', { exact: true }).fill('Demo');
  await modal.getByLabel('Classe', { exact: true }).fill('2ª primaria');
  await modal.getByLabel('Nome e cognome del tutore').fill('Genitore Alice Demo');
  await modal.getByRole('button', { name: 'Salva', exact: true }).click();
  await expect(modal).not.toBeVisible();
  await page.getByRole('button', { name: /Alice Demo.*2ª primaria/ }).click();
  await page.getByRole('button', { name: 'Aggiungi', exact: true }).click();
  modal = page.getByRole('dialog');
  await modal.getByLabel('Nome dell’accordo').fill('Retta Alice');
  await modal.getByLabel('Importo (€)', { exact: true }).fill('180,00');
  await modal.getByLabel('Inizio validità').fill('2026-10-01');
  await modal.getByRole('button', { name: 'Salva', exact: true }).click();
  await page.getByRole('button', { name: 'Prepara rette', exact: true }).click();
  await page.getByRole('button', { name: 'Emetti scadenze', exact: true }).click();
  await expect(page.getByTestId('remaining')).toHaveText('180,00 €');
  await page.getByRole('button', { name: /Registra pagamento Alice Demo/ }).click();
  modal = page.getByRole('dialog');
  await modal.getByLabel('Importo ricevuto (€)').fill('200');
  await modal.getByRole('button', { name: 'Registra pagamento', exact: true }).click();
  await expect(modal.getByRole('alert')).toContainText('supera il residuo');
  await modal.getByLabel('Importo ricevuto (€)').fill('60,01');
  await modal.getByLabel('Nota (facoltativa)').fill('Acconto prova completa');
  await modal.getByRole('button', { name: 'Registra pagamento', exact: true }).click();
  await expect(page.getByTestId('remaining')).toHaveText('119,99 €');
  await page.reload();
  await page.getByRole('textbox', { name: 'Cerca un bambino' }).fill('Alice');
  await page.getByRole('button', { name: /Alice Demo.*2ª primaria/ }).click();
  await expect(page.getByTestId('remaining')).toHaveText('119,99 €');
  await page.screenshot({ path: screenshotPath('scheda-bambino.png'), fullPage: true });
  await nav(page, 'Storico');
  await page.getByRole('row').filter({ hasText: 'Alice Demo' }).getByRole('button', { name: 'Storna' }).click();
  modal = page.getByRole('dialog');
  await modal.getByLabel('Motivo dello storno').fill('Doppia registrazione di prova');
  await modal.getByRole('button', { name: 'Conferma storno' }).click();
  await expect(page.getByRole('row').filter({ hasText: 'Alice Demo' })).toContainText('Stornato');
  await nav(page, 'Il tuo archivio');
  const downloading = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Esporta backup', exact: true }).click();
  const file = await downloading;
  const stream = await file.createReadStream();
  const chunks: Buffer[] = []; for await (const chunk of stream!) chunks.push(Buffer.from(chunk));
  const backup = JSON.parse(Buffer.concat(chunks).toString());
  expect(backup.children).toHaveLength(5); expect(backup.guardians).toHaveLength(5);
  expect(backup.payments.find((p: { note: string }) => p.note === 'Acconto prova completa').voidReason).toBe('Doppia registrazione di prova');
  await page.getByLabel('File backup da ripristinare').setInputFiles({ name: 'backup.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(backup)) });
  modal = page.getByRole('dialog');
  await expect(modal).toContainText('5 bambini · 5 tutori');
  await modal.getByRole('checkbox').check();
  await modal.getByRole('button', { name: 'Sostituisci archivio' }).click();
  await expect(modal).not.toBeVisible();
  await page.reload(); await nav(page, 'Bambini');
  await page.getByRole('button', { name: /Alice Demo.*2ª primaria/ }).click();
  await expect(page.getByTestId('remaining')).toHaveText('180,00 €');
});

